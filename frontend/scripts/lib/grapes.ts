/**
 * Канонические сорта: ключи для сравнения вин между собой и для правил сомелье.
 *
 * В карточке и в фильтре каталога остаётся формулировка винодельни — это факт
 * каталога. Канон нужен только машине: без него «Шираз» и «Сира» — разные сорта,
 * и похожие вина не находят друг друга.
 *
 * Сводятся только синонимы одного и того же сорта. Родственные, но разные сорта
 * (Бастардо и Бастардо Магарачский, Красностоп Анапский и Золотовский) не сливаются —
 * их близость учитывает функция схожести на уровне семейства.
 */

const SYNONYMS: Readonly<Record<string, string>> = {
  шираз: 'Сира',
  'сира (шираз)': 'Сира',
  'рислинг рейнский': 'Рислинг',
  'пино черный': 'Пино Нуар',
  'пино фран': 'Пино Нуар',
  'пино гриджио': 'Пино Гри',
  'пино менье': 'Менье',
  'мюллер тургау': 'Мюллер-Тургау',
  бьянка: 'Бианка',
  'кокур белый': 'Кокур',
  мцване: 'Мцване Кахетинский',
  кумшацкий: 'Кумшацкий белый',
  совиньон: 'Совиньон Блан',
  'мускат блан': 'Мускат Белый',
  'мускат мелкозернистый': 'Мускат Белый',
  'москато-джалло': 'Мускат Желтый',
  'мускат джалло': 'Мускат Желтый',
  'траминер розовый': 'Гевюрцтраминер',
  грюнер: 'Грюнер Вельтлинер',
  мадраса: 'Мадраса',
  'антей магарачский': 'Антей Магарачский',
  'ркацители оранж': 'Ркацители',
  примитиво: 'Зинфандель',
}

/** Две записи сорта в одной строке — делим на два сорта. */
const SPLITS: Readonly<Record<string, readonly string[]>> = {
  'пино черный (пино нуар) и мерло': ['Пино Нуар', 'Мерло'],
  'пино черный (пино нуар) и сира (шираз)': ['Пино Нуар', 'Сира'],
}

/** Заглушки вместо сорта: у Массандры и Союз-Вина. Это «сорт неизвестен», а не сорт. */
const PLACEHOLDERS = new Set(['белые сорта винограда', 'красные сорта винограда'])

const keyOf = (value: string): string => value.trim().toLowerCase().replace(/ё/g, 'е')

/** Сорта одной позиции → канонические, без дублей, порядок исходный. */
export function canonicalGrapes(grapes: readonly string[]): string[] {
  const out: string[] = []
  const seen = new Set<string>()
  for (const grape of grapes) {
    const key = keyOf(grape)
    if (PLACEHOLDERS.has(key)) continue
    const parts = SPLITS[key] ?? [SYNONYMS[key] ?? grape.trim()]
    for (const part of parts) {
      const partKey = keyOf(part)
      if (seen.has(partKey)) continue
      seen.add(partKey)
      out.push(part)
    }
  }
  return out
}
